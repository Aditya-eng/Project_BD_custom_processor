"""Galileo E1 and E5a/E5b codes (OS SIS ICD sections 3.4, 3.5 and Annex C).

E1-B/E1-C are memory codes, read from tables/galileo_e1_codes.txt. E5 codes
are generated by two 14-stage LFSRs (Table 16 taps, register 1 all ones,
register 2 from Tables 17-20), truncated to 10230 chips. Register convention
(verified against the ICD's attached codes, see tools/import_galileo_icd.py):
cells c1..c14, feedback = XOR of c_j where tap bit j (octal, LSB = j=0) is set,
shift c_j -> c_{j+1}, feedback into c1, output = c14.

Copyright (c) European Union 2025 for the code values; see the table headers.
"""
from functools import lru_cache
from pathlib import Path

import numpy as np

E1_LEN = 4092
E1_CHIP_RATE = 1.023e6
E1_FREQ = 1575.42e6
E5_LEN = 10230
E5_CHIP_RATE = 10.23e6
E5A_FREQ = 1176.45e6
E5B_FREQ = 1207.14e6
_R = 14


def hex_to_bits(hx: str) -> np.ndarray:
    """Annex C convention: leftmost hex symbol = first four chips, MSB first."""
    return np.array([(int(c, 16) >> (3 - k)) & 1 for c in hx for k in range(4)], dtype=np.uint8)


def lfsr_code(taps1: int, taps2: int, start2: int, n: int = E5_LEN) -> np.ndarray:
    # Register as an int: bit k holds cell k+1. Tap bit j (j = 1..14) selects cell j.
    m1 = (taps1 >> 1) & 0x3FFF
    m2 = (taps2 >> 1) & 0x3FFF
    r1, r2 = 0x3FFF, start2 & 0x3FFF          # register 1 all ones; start bit j=1 at LSB
    out = np.empty(n, dtype=np.uint8)
    for i in range(n):
        out[i] = ((r1 ^ r2) >> 13) & 1          # cell 14
        r1 = ((r1 << 1) & 0x3FFF) | ((r1 & m1).bit_count() & 1)
        r2 = ((r2 << 1) & 0x3FFF) | ((r2 & m2).bit_count() & 1)
    return out


@lru_cache(maxsize=None)
def _e1_table():
    rows = {}
    path = Path(__file__).parent / "tables" / "galileo_e1_codes.txt"
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        comp, prn, hx = line.split(";")
        rows[(comp, int(prn))] = hx
    return rows


def e1_code(prn: int, component: str = "B") -> np.ndarray:
    """4092-chip E1-B or E1-C primary code (logic 0/1)."""
    return hex_to_bits(_e1_table()[("E1" + component, prn)])[:E1_LEN]


def e5_code(prn: int, component: str = "aI") -> np.ndarray:
    """10230-chip E5a-I/E5a-Q/E5b-I/E5b-Q primary code: component in aI, aQ, bI, bQ."""
    from .tables.galileo_tables import E5_PARAMS
    t1, t2, starts = E5_PARAMS["E5" + component]
    return lfsr_code(t1, t2, starts[prn])


def secondary(length: int, index: int = 1) -> tuple:
    from .tables.galileo_tables import SECONDARY
    return tuple(int(b) for b in SECONDARY[(length, index)])


# Secondary-code assignment (Table 24 and section 3.6): per SVID n
def e1c_secondary(prn: int) -> tuple:
    return secondary(25, 1)


def e5ai_secondary(prn: int) -> tuple:
    return secondary(20, 1)


def e5aq_secondary(prn: int) -> tuple:
    return secondary(100, prn)
