#!/usr/bin/env python3
"""Import the B1I code table from the official BDS-SIS-ICD-B1I PDF (needs poppler-utils: pdftotext).

usage: import_bds_b1i.py <BDS-SIS-ICD-B1I-3.0.pdf>  -> model/bdmodel/tables/bds_b1i_table.py

The ICD prints no example chips, so the checks are against what it does state:
- the generator polynomials and initial phases in section 4.3 equal the constants
  in model/bdmodel/bds_b1i.py (whose feedback stages were read from Figure 4-1);
- Table 4-1 lists ranging codes 1-63 exactly once, each with 2 or 3 distinct G2 stages;
- every code is a *balanced* Gold code (1024 ones in 2047 chips), as section 4.3
  says, and all 63 truncated codes are distinct;
- the NH code in section 5.2.1 equals bds_b1i.NH20.
Wrong conventions (e.g. G1 output from stage 1, or the G2 polynomial reversed)
leave dozens of codes unbalanced, so the balance check does discriminate.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel import bds_b1i  # noqa: E402


def poly_stages(expr):
    """'1+X+X7+X8' -> (1, 7, 8): the exponents >= 1 (register stages)."""
    terms = expr.replace(" ", "").split("+")
    assert terms[0] == "1", expr
    return tuple(1 if t == "X" else int(t[1:]) for t in terms[1:])


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    ver = re.search(r"BDS-SIS-ICD-B1I-(\d+\.\d+)\s*\n\s*(\d{4}-\d{2})", text)
    assert ver, "document identifier not found"

    g1 = re.search(r"G1\(X\)=([1X0-9+ ]+)\n", text).group(1)
    g2 = re.search(r"G2\(X\)=([1X0-9+ ]+)\n", text).group(1)
    assert poly_stages(g1) == bds_b1i.G1_FEEDBACK, g1
    assert poly_stages(g2) == bds_b1i.G2_FEEDBACK, g2
    init = re.findall(r"^\s*G[12]: ([01]{11})[;.]", text, re.M)
    assert init == [bds_b1i.INIT, bds_b1i.INIT], init

    rows = {}
    for m in re.finditer(r"^\s*(\d+)\s+(GEO|MEO/IGSO) satellite\s+(\d+)\s+([\d⊕]+)\s*$", text, re.M):
        prn = int(m.group(3))
        assert int(m.group(1)) == prn and prn not in rows, prn
        taps = tuple(int(x) for x in m.group(4).split("⊕"))
        assert len(taps) in (2, 3) and len(set(taps)) == len(taps) and max(taps) <= 11, (prn, taps)
        rows[prn] = (m.group(2), taps)
    assert sorted(rows) == list(range(1, 64)), sorted(set(range(1, 64)) ^ set(rows))

    codes = set()
    for prn, (_, taps) in rows.items():
        g = bds_b1i.gold(taps)
        assert int(g.sum()) == 1024, (prn, int(g.sum()))       # balanced Gold code
        codes.add(g[:bds_b1i.B1I_LEN].tobytes())
    assert len(codes) == 63

    nh = re.search(r"NH code\s*\n?\s*\(([01]{20})\)", text) or re.search(r"\(([01]{20})\) with length of 20", text)
    assert nh and tuple(int(c) for c in nh.group(1)) == bds_b1i.NH20

    src = f"BDS-SIS-ICD-B1I-{ver.group(1)} ({ver.group(2)}), PDF sha256 {digest}"
    out = ROOT / "model" / "bdmodel" / "tables" / "bds_b1i_table.py"
    body = [f"# Generated by tools/import_bds_b1i.py from {src},",
            "# Table 4-1. Do not edit.",
            "# B1I_CODES[prn] = (satellite type, G2 stages XORed for the phase assignment)",
            "B1I_CODES = {"]
    body += [f"    {p}: (\"{'GEO' if t == 'GEO' else 'MEO/IGSO'}\", {taps}),"
             for p, (t, taps) in sorted(rows.items())]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out}: 63 codes, all balanced and distinct; polynomials, initial phases "
          f"and NH code match ({src})")


if __name__ == "__main__":
    main()
