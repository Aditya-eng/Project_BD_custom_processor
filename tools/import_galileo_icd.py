#!/usr/bin/env python3
"""Import Galileo primary and secondary codes from the official OS SIS ICD PDF.

usage: import_galileo_icd.py <Galileo_OS_SIS_ICD.pdf>

Sources inside the one PDF (needs poppler-utils: pdfdetach, pdftotext):
- electronic Annex C attachments C3..C8 (E5a-I, E5a-Q, E5b-I, E5b-Q, E1-B, E1-C)
- Table 16 (E5 feedback taps), Tables 17-20 (E5 base register 2 start values and
  first 24 chips), Tables 22-23 (secondary codes), section 3.5.1 (CS25 example).

Nothing is written unless every check passes:
- each attachment has the code count and length of Table 108;
- every E5 code generated by LFSR from Tables 16-20 equals the attached code
  over its full 10230 chips, and its first 24 chips equal the table column;
- CS25 decodes to the binary sequence printed in section 3.5.1.
The E5 checks exercise the same attachment parser that reads the E1 memory
codes, which have no second representation in the ICD.

Outputs (model/bdmodel/tables/): galileo_e1_codes.txt (E1-B/E1-C hex, as in
Annex C), galileo_tables.py (E5 generator parameters, SHA-256 of every E5
code, secondary codes).

Copyright (c) European Union 2025. Source: European GNSS (Galileo) Open
Service Signal-In-Space ICD, https://www.gsc-europa.eu/electronic-library/
programme-reference-documents. Used under the ICD's Annex H authorisation.
"""
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel.galileo import E5_LEN, E1_LEN, hex_to_bits, lfsr_code  # noqa: E402

ATTACH = {"E5aI": "C3_E5aI.txt", "E5aQ": "C4_E5aQ.txt", "E5bI": "C5_E5bI.txt",
          "E5bQ": "C6_E5bQ.txt", "E1B": "C7_E1B.txt", "E1C": "C8_E1C.txt"}
TABLE_FOR = {"E5aI": "17", "E5aQ": "18", "E5bI": "19", "E5bQ": "20"}
TAP_ROW = {"E5aI": "E5a-I", "E5aQ": "E5a-Q", "E5bI": "E5b-I", "E5bQ": "E5b-Q"}
CS25_PRINTED = "0011100000001010110110010"   # section 3.5.1 example


def read_attachments(pdf, tmp):
    subprocess.run(["pdfdetach", "-saveall", "-o", tmp, str(pdf)], check=True)
    codes = {}
    for comp, fname in ATTACH.items():
        n = E1_LEN if comp.startswith("E1") else E5_LEN
        nhex = -(-n // 4)
        rows = {}
        for line in (Path(tmp) / fname).read_text().split():
            name, hx = line.split(";")
            assert len(hx) == nhex and re.fullmatch(r"[0-9A-F]+", hx), (comp, name)
            pad = hex_to_bits(hx)[n:]
            assert set(pad) <= {0}, (comp, name, "non-zero fill")
            rows[int(name.rsplit("_", 1)[1])] = hx
        assert sorted(rows) == list(range(1, 51)), (comp, sorted(rows)[:5])
        codes[comp] = rows
    return codes


def read_tables(pdf):
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    assert CS25_PRINTED in text.replace(" ", ""), "CS25 example not found"
    issue = re.search(r"OS SIS ICD, (Issue [0-9.]+, \w+ \d{4})", text).group(1)
    taps = {}
    for comp, row in TAP_ROW.items():
        m = re.search(rf"^\s*{row}\s+14\s+([0-7]+)\s+([0-7]+)\s*$", text, re.M)
        taps[comp] = (int(m.group(1), 8), int(m.group(2), 8))
    starts = {}
    lines = text.splitlines()
    for comp, tno in TABLE_FOR.items():
        i0 = max(i for i, l in enumerate(lines) if re.search(rf"Table {tno}: Base Register 2 Start", l, re.I))
        rows = {}
        for l in lines[i0 + 1:]:
            if re.search(r"Table \d+:", l):
                break
            for m in re.finditer(r"(\d+)\s+([0-7]{5})\s+([0-9A-F]{6})", l):
                rows[int(m.group(1))] = (int(m.group(2), 8), m.group(3))
        assert sorted(rows) == list(range(1, 51)), (comp, len(rows))
        starts[comp] = rows
    sec = {}
    for m in re.finditer(r"^\s*CS(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+([0-9A-F]+)\s*$", text, re.M):
        ident, length, nhex, fill, hx = m.groups()
        length = int(length)
        index = int(ident[len(str(length)):])
        assert len(hx) == int(nhex) and 4 * int(nhex) - length == int(fill)
        sec[(length, index)] = "".join(map(str, hex_to_bits(hx)[:length]))
    assert sec[(25, 1)] == CS25_PRINTED
    assert sorted(k for k in sec if k[0] == 100) == [(100, i) for i in range(1, 101)]
    return taps, starts, sec, issue


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    with tempfile.TemporaryDirectory() as tmp:
        att = read_attachments(pdf, tmp)
    taps, starts, sec, issue = read_tables(pdf)

    e5_hash = {}
    for comp in TABLE_FOR:
        t1, t2 = taps[comp]
        for prn, (s2, first24) in starts[comp].items():
            gen = lfsr_code(t1, t2, s2)
            attached = hex_to_bits(att[comp][prn])[:E5_LEN]
            assert list(gen) == list(attached), (comp, prn, "LFSR != attachment")
            assert "%06X" % int("".join(map(str, gen[:24])), 2) == first24, (comp, prn)
            e5_hash[(comp, prn)] = hashlib.sha256(bytes(gen)).hexdigest()

    tables = ROOT / "model" / "bdmodel" / "tables"
    header = [
        f"Galileo OS SIS ICD {issue}; PDF sha256 {digest}",
        "Copyright (c) European Union 2025. Source: European GNSS (Galileo) Open Service",
        "Signal-In-Space ICD, https://www.gsc-europa.eu/electronic-library/programme-reference-documents",
        "Used under the ICD's Annex H authorisation (accepted by the project owner, see docs/LICENSES.md).",
        "Generated by tools/import_galileo_icd.py - do not edit.",
    ]
    e1 = ["# " + h for h in header] + ["# component;code number;hex (Annex C convention)"]
    for comp in ("E1B", "E1C"):
        e1 += [f"{comp};{prn};{att[comp][prn]}" for prn in range(1, 51)]
    (tables / "galileo_e1_codes.txt").write_text("\n".join(e1) + "\n")

    py = ["# " + h for h in header] + [
        "# E5 generator parameters (Tables 16-20): component -> (taps reg1, taps reg2, {prn: start reg2})",
        "E5_PARAMS = {"]
    for comp in TABLE_FOR:
        t1, t2 = taps[comp]
        st = ", ".join(f"{p}: 0o{starts[comp][p][0]:05o}" for p in range(1, 51))
        py.append(f"    \"{comp}\": (0o{t1:o}, 0o{t2:o}, {{{st}}}),")
    py += ["}", "",
           "# SHA-256 of each attached E5 code (bytes of 0/1 chips); the LFSR must reproduce them.",
           "E5_SHA256 = {"]
    py += [f"    (\"{c}\", {p}): \"{h}\"," for (c, p), h in sorted(e5_hash.items())]
    py += ["}", "", "# Secondary codes (Tables 22-23): (length, index) -> chips, first in time first",
           "SECONDARY = {"]
    py += [f"    ({l}, {i}): \"{b}\"," for (l, i), b in sorted(sec.items())]
    py += ["}", ""]
    (tables / "galileo_tables.py").write_text("\n".join(py))
    print(f"ok: 300 primary codes, E5 LFSR == attachment for 200 codes, "
          f"{len(sec)} secondary codes; PDF sha256 {digest}")


if __name__ == "__main__":
    main()
