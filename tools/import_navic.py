#!/usr/bin/env python3
"""Generate the NavIC L5 SPS code table LOCALLY from your own copy of the ISRO ICD
(ISRO-IRNSS-ICD-SPS-1.1; needs poppler-utils: pdftotext).

usage: import_navic.py <ISRO-IRNSS-ICD-SPS-1.1.pdf>  -> model/bdmodel/tables/navic_l5_table.py

The output file is in .gitignore and must not be committed or redistributed: the ICD's
cover page says its contents shall not be copied, in whole or in part, without ISRO's
prior written consent (docs/LICENSES.md).

Nothing is written unless, for every row of Table 7 (L5 and S columns), the code
generated from the G2 initial state (stage 10 first, model/bdmodel/gps_ca.py) starts with
the printed first 10 chips (octal: first digit one bit, then three octal digits).
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel.gps_ca import ca_code_from_g2_init  # noqa: E402

KNOWN_SHA256 = "321573a6903ebc5d7392a1baa26795ccd6997100449cb79836f849498ea8216f"  # version 1.1
ROW = re.compile(r"(\d+) ([01]{10}) ([01][0-7]{3}) ([01]{10}) ([01][0-7]{3})")


def bits10(octal: str):
    return [int(octal[0])] + [int(b) for b in format(int(octal[1:], 8), "09b")]


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    if digest != KNOWN_SHA256:
        print(f"note: PDF sha256 {digest} is not the version 1.1 file this tool was written "
              f"against; the row checks below still apply")
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    lines = [re.sub(r"[ \t]+", " ", l.strip()) for l in text.splitlines()]
    head = [i for i, l in enumerate(lines) if l == "Table 7: Code Phase assignment for SPS signals"]
    assert len(head) == 1, head
    rows = {}
    for l in lines[head[0] + 1:head[0] + 80]:
        m = ROW.fullmatch(l)
        if m:
            prn = int(m.group(1))
            assert prn not in rows, prn
            rows[prn] = m.groups()[1:]
    assert sorted(rows) == list(range(1, 15)), sorted(rows)
    for prn, (i5, f5, i_s, f_s) in rows.items():
        for init, first in ((i5, f5), (i_s, f_s)):
            c = ca_code_from_g2_init([int(b) for b in init])
            assert list(c[:10]) == bits10(first), prn

    out = ROOT / "model" / "bdmodel" / "tables" / "navic_l5_table.py"
    body = ["# LOCAL FILE generated by tools/import_navic.py from ISRO-IRNSS-ICD-SPS-1.1",
            f"# (PDF sha256 {digest}), Table 7, L5 column.",
            "# Do not commit or redistribute (ISRO copyright; see docs/LICENSES.md).",
            "# NAVIC_L5_G2_INIT[prn] = G2 initial state, stage 10 first",
            "NAVIC_L5_G2_INIT = {"]
    body += [f'    {p}: "{r[0]}",' for p, r in sorted(rows.items())]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out} (local only): {len(rows)} PRNs, L5 and S first 10 chips verified")


if __name__ == "__main__":
    main()
