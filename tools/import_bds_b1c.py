#!/usr/bin/env python3
"""Import the B1C code tables from the official BDS-SIS-ICD-B1C PDF (needs poppler-utils: pdftotext).

usage: import_bds_b1c.py <BDS-SIS-ICD-B1C-1.0.pdf>  -> model/bdmodel/tables/bds_b1c_table.py

Nothing is written unless every check passes:
- the worked example in 5.2.1 (PRN 1 data, first 24 chips 101011111111011001001110 =
  octal 53773116) is found and agrees with the generated code;
- Tables 5-2 and 5-3 list PRN 1-63 once each, w in 1..5121, p in 1..10243, and every
  one of the 126 primary codes (Weil, length 10243, truncated to 10230) reproduces its
  printed first 24 and last 24 chips;
- Table 5-4 lists PRN 1-63, w in 1..1803, p in 1..3607, and every pilot secondary
  code (Weil, length 3607, truncated to 1800) reproduces its printed first/last 24 chips.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel import bds_b1c, weil  # noqa: E402


def bits24(octal):
    return format(int(octal, 8), "024b")


def table(lines, title):
    """PRN -> (w, p, first24, last24) from the title line to the next section."""
    i = next(k for k, l in enumerate(lines) if l.strip().startswith(title))
    out = {}
    for l in lines[i + 1:]:
        if re.match(r"\s*5\.\d", l) or re.match(r"\s*Table 5-", l):
            break
        m = re.fullmatch(r"(\d+)\s+(\d+)\s+(\d+)\s+([0-7]{8})\s+([0-7]{8})", l.strip())
        if m:
            prn = int(m.group(1))
            assert prn not in out, (title, prn)
            out[prn] = (int(m.group(2)), int(m.group(3)), m.group(4), m.group(5))
    assert sorted(out) == list(range(1, 64)), (title, sorted(set(range(1, 64)) ^ set(out)))
    return out


def check(rows, n, n0, w_max, what):
    for prn, (w, p, first, last) in rows.items():
        assert 1 <= w <= w_max and 1 <= p <= n, (what, prn, w, p)
        c = "".join(map(str, weil.weil_truncated(w, p, n0, n)))
        assert c[:24] == bits24(first) and c[-24:] == bits24(last), (what, prn)


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    lines = text.splitlines()
    ver = re.search(r"BDS-SIS-ICD-B1C-(\d+\.\d+)\s*\n\s*(\d{4}-\d{2})", text)
    assert ver, "document identifier not found"

    data = table(lines, "Table 5-2 Primary code parameters")
    pilot = table(lines, "Table 5-3 Primary code parameters")
    sec = table(lines, "Table 5-4 Secondary code parameters")

    ex = re.search(r"PRN 1\s+are\s+([01]{24}) in binary, or equivalently, ([0-7]{8}) in octal", text)
    assert ex and bits24(ex.group(2)) == ex.group(1) and data[1][2] == ex.group(2), "5.2.1 example"

    check(data, bds_b1c.PRIMARY_N, bds_b1c.B1C_LEN, 5121, "data")
    check(pilot, bds_b1c.PRIMARY_N, bds_b1c.B1C_LEN, 5121, "pilot")
    check(sec, bds_b1c.SECONDARY_N, bds_b1c.SECONDARY_LEN, 1803, "secondary")

    src = f"BDS-SIS-ICD-B1C-{ver.group(1)} ({ver.group(2)}), PDF sha256 {digest}"
    out = ROOT / "model" / "bdmodel" / "tables" / "bds_b1c_table.py"
    body = [f"# Generated by tools/import_bds_b1c.py from {src},",
            "# Tables 5-2, 5-3 and 5-4. Do not edit.",
            "# B1C_CODES[prn] = {'D': (w, p) data primary, 'P': (w, p) pilot primary,",
            "#                   'S': (w, p) pilot secondary}  (Weil phase difference, truncation point)",
            "B1C_CODES = {"]
    body += [f"    {p}: {{\"D\": {data[p][:2]}, \"P\": {pilot[p][:2]}, \"S\": {sec[p][:2]}}},"
             for p in range(1, 64)]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out}: 126 primary codes and 63 pilot secondary codes match their printed "
          f"first/last 24 chips ({src})")


if __name__ == "__main__":
    main()
