#!/usr/bin/env python3
"""Import the L5 code-phase tables (Tables 3-Ia, 3-Ib and 6-II) from IS-GPS-705J.

Table 6-II adds PRN 64-210 (QZSS L5 uses 193-202; SBAS L5 is also selected from it).

Input: a plain-text extraction of the official PDF (the PDF itself is not
stored in this repository). Every row is cross-checked before anything is
written: advancing an all-ones XB register by the listed number of chips must
reproduce the listed "initial XB code state" (first 13 chips, rightmost bit
first). The two columns are independent statements of the same fact, so a
transcription or parsing error in either fails the import.

usage: import_is705.py <is-gps-705j.txt>   -> model/bdmodel/tables/gps_l5_table.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel.gps_l5 import xb_from_advance  # noqa: E402


def parse(text, prefix="Table 3-I", title="Code Phase Assignments"):
    lines = text.splitlines()
    heads = [i for i, l in enumerate(lines)
             if l.startswith(prefix) and title in l and "...." not in l]
    starts = []
    for h in heads:
        if starts and h - starts[-1] < 3:      # header line repeated in the extraction
            continue
        starts.append(h)
    rows = {}
    for h in starts:
        nums, states = [], []
        for l in lines[h + 1:h + 400]:
            if l.startswith(("*", "NOTE", "-- ")):
                if states:
                    break
                continue
            if re.fullmatch(r"[01]{13}", l):
                states.append(l)
            elif re.fullmatch(r"\d+", l):
                nums.append(int(l))
        n = len(states) // 2
        assert len(nums) == 3 * n and len(states) == 2 * n, (lines[h], len(nums), len(states))
        prn, adv_i, adv_q = nums[:n], nums[n:2 * n], nums[2 * n:]
        for k in range(n):       # columns: all I5 states, then all Q5 states
            rows[prn[k]] = (adv_i[k], adv_q[k], states[k], states[n + k])
    return rows


def main():
    text = Path(sys.argv[1]).read_text()
    rows = parse(text)
    assert sorted(rows) == list(range(1, 64)), sorted(rows)
    ext = parse(text, "Table 6-II", "Additional Code Phase Assignments")
    assert sorted(ext) == list(range(64, 211)), sorted(set(range(64, 211)) ^ set(ext))
    rows.update(ext)
    for prn, (ai, aq, si, sq) in rows.items():
        for adv, state in ((ai, si), (aq, sq)):
            assert xb_from_advance(adv) == state, (prn, adv, state)
    out = ROOT / "model" / "bdmodel" / "tables" / "gps_l5_table.py"
    body = ["# Generated by tools/import_is705.py from IS-GPS-705J (01-AUG-2022),",
            "# Table 3-Ia (PRN 1-37), Table 3-Ib (PRN 38-63) and Table 6-II (PRN 64-210). Do not edit.",
            "# PRN: (XB advance I5, XB advance Q5, initial XB state I5, initial XB state Q5)",
            "# States: first 13 XB chips, rightmost bit first out (ICD notation).",
            "L5_CODE_PHASES = {"]
    body += [f"    {p}: ({ai}, {aq}, \"{si}\", \"{sq}\")," for p, (ai, aq, si, sq) in sorted(rows.items())]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out} ({len(rows)} PRNs, all cross-checked)")


if __name__ == "__main__":
    main()
