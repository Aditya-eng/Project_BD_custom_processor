#!/usr/bin/env python3
"""Import the additional C/A-code table (PRN 64-210) from the official IS-GPS-200N PDF
(needs poppler-utils: pdftotext).

usage: import_is200_ca.py <IS-GPS-200N.pdf>  -> model/bdmodel/tables/gps_ca_ext_table.py

Table 6-I gives, per PRN, the G2 delay (chips), the initial G2 setting (octal) and the
first 10 chips (octal); in both octal columns the first digit is the first bit and the
other three digits are the remaining 9 bits. PRN 120-158 are the SBAS codes and
193-202 the QZSS L1 C/A codes (IS-GPS-200N 6.3.6.1 reserves 120-158 for SBAS).

Nothing is written unless every row passes three independent checks:
  1. the code generated from the G2 delay (model/bdmodel/gps_ca.py) starts with the
     printed first 10 chips;
  2. G1 xor a G2 register started at the printed initial G2 setting (first digit =
     stage 10) equals the delay-generated code over the whole 1023-chip period;
  3. the first 10 chips are the complement of the initial G2 setting (G1 starts at all
     ones, so its first 10 output chips are ones).
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel.gps_ca import ca_code_from_delay, ca_code_from_g2_init  # noqa: E402

ROW = re.compile(r"(\d+) (\d+) ([01][0-7]{3}) ([01][0-7]{3}) \d+ P\d+\(t\+\d+\) [0-7]{4}")


def bits10(octal: str):
    """IS-GPS-200 10-bit octal: first digit is one bit, then three octal digits."""
    return [int(octal[0])] + [int(b) for b in format(int(octal[1:], 8), "09b")]


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    lines = [re.sub(r"[ \t]+", " ", l.strip()) for l in text.splitlines()]
    issue = re.search(r"IS-GPS-200([A-Z])\s*\n\s*(\d{2}-[A-Z]{3}-\d{4})", text)

    heads = [i for i, l in enumerate(lines)
             if re.fullmatch(r"Table 6-I\.? Additional C/A-/P-Code Phase Assignments "
                             r"\(sheet \d of 5\)", l)]
    assert len(heads) == 5, heads
    rows = {}
    for h in heads:
        for l in lines[h + 1:h + 60]:
            if l.startswith("* In the octal"):
                break
            m = ROW.fullmatch(l)
            if m:
                prn = int(m.group(1))
                assert prn not in rows, prn
                rows[prn] = (int(m.group(2)), m.group(3), m.group(4))
    assert sorted(rows) == list(range(64, 211)), sorted(set(range(64, 211)) ^ set(rows))

    for prn, (delay, init, first10) in rows.items():
        assert 0 < delay < 1023, prn
        assert list(ca_code_from_delay(delay)[:10]) == bits10(first10), ("first10", prn)
        assert (ca_code_from_g2_init(bits10(init)) == ca_code_from_delay(delay)).all(), ("init", prn)
        assert [1 - b for b in bits10(init)] == bits10(first10), ("complement", prn)

    src = f"IS-GPS-200{issue.group(1)} ({issue.group(2)}), PDF sha256 {digest}" if issue else digest
    out = ROOT / "model" / "bdmodel" / "tables" / "gps_ca_ext_table.py"
    body = [f"# Generated by tools/import_is200_ca.py from {src},",
            "# Table 6-I (Additional C/A-Code Phase Assignments). Do not edit.",
            "# CA_EXT[prn] = (G2 delay in chips, initial G2 setting, first 10 chips); octal as",
            "# printed: the first digit is the first bit, the other three the remaining 9 bits.",
            "CA_EXT = {"]
    body += [f'    {p}: ({d}, "{i}", "{f}"),' for p, (d, i, f) in sorted(rows.items())]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out}: {len(rows)} PRNs, all three checks passed ({src})")


if __name__ == "__main__":
    main()
