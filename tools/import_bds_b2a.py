#!/usr/bin/env python3
"""Import the B2a code tables from the official BDS-SIS-ICD-B2a PDF (needs poppler-utils: pdftotext).

usage: import_bds_b2a.py <BDS-SIS-ICD-B2a-1.0.pdf>  -> model/bdmodel/tables/bds_b2a_table.py

Nothing is written unless every check passes:
- the four generator polynomials in 5.2.1 equal model/bdmodel/bds_b2a.POLY;
- Tables 5-2 and 5-3 list PRN 1-63 once each; every one of the 126 primary codes
  generated from its register-2 initial value reproduces the printed first 24 and
  last 24 chips;
- Table 5-4 lists PRN 1-63 with w in 1..510 and p in 1..1021; every pilot
  secondary code built from (w, p) reproduces its printed first 24 and last 24 chips;
- the data secondary code is the printed 00010.

ICD inconsistency handled explicitly: 5.2.1 says the data and pilot generators of a
satellite "start with the same initial bit values", but Tables 5-2 and 5-3 give
different values for PRN 61, 62 and 63. Each of those rows reproduces its own
printed first/last 24 chips, so the tables are self-consistent and are used as
printed. The import asserts that exactly PRN 61-63 differ.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel import bds_b2a  # noqa: E402


def bits24(octal):
    return format(int(octal, 8), "024b")


def rows_after(lines, title, pattern):
    """Rows matching `pattern` from the title line until the next section."""
    i = next(k for k, l in enumerate(lines) if l.strip().startswith(title))
    out = {}
    for l in lines[i + 1:]:
        if re.match(r"\s*5\.\d", l) or re.match(r"\s*Table 5-", l):
            break
        m = re.fullmatch(pattern, l.strip())
        if m:
            prn = int(m.group(1))
            assert prn not in out, (title, prn)
            out[prn] = m.groups()[1:]
    assert sorted(out) == list(range(1, 64)), (title, sorted(set(range(1, 64)) ^ set(out)))
    return out


def poly(line):
    """'g1 ( x ) = 1 + x + x 5 + x11 + x13' -> (1, 5, 11, 13). The PDF's symbol font
    extracts '=' and '+' as U+F03D and U+F02B."""
    body = line.split(")", 1)[1].replace("", "=").replace("", "+")
    m = re.fullmatch(r"\s*=\s*1((?:\s*\+\s*x\s*\d*)+)\s*", body)
    assert m, repr(line)
    exps = [int(e) if e else 1 for e in re.findall(r"x\s*(\d*)", m.group(1))]
    assert exps == sorted(set(exps)), line
    return tuple(exps)


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    lines = text.splitlines()
    ver = re.search(r"BDS-SIS-ICD-B2a\s*-(\d+\.\d+)\s*\n\s*(\d{4}-\d{2})", text)
    assert ver, "document identifier not found"

    polys = [poly(l) for l in lines if re.match(r"\s*g\s*[12]\s*\(\s*x\s*\)", l)]
    assert polys == [*bds_b2a.POLY["D"], *bds_b2a.POLY["P"]], polys

    row = r"(\d+)\s+([01]{13})\s+([0-7]{8})\s+([0-7]{8})"
    data = rows_after(lines, "Table 5-2 Primary code parameters", row)
    pilot = rows_after(lines, "Table 5-3 Primary code parameters", row)
    sec = rows_after(lines, "Table 5-4 Secondary code parameters",
                     r"(\d+)\s+(\d+)\s+(\d+)\s+([0-7]{8})\s+([0-7]{8})")

    differ = [prn for prn in range(1, 64) if data[prn][0] != pilot[prn][0]]
    assert differ == [61, 62, 63], differ                  # see module docstring
    for prn in range(1, 64):
        for comp, (init2, first, last) in (("D", data[prn]), ("P", pilot[prn])):
            c = "".join(map(str, bds_b2a.primary(comp, init2)))
            assert c[:24] == bits24(first) and c[-24:] == bits24(last), (prn, comp)
        w, p, first, last = sec[prn]
        w, p = int(w), int(p)
        assert 1 <= w <= 510 and 1 <= p <= bds_b2a.WEIL_N, (prn, w, p)
        s = "".join(map(str, bds_b2a.weil_truncated(w, p)))
        assert s[:24] == bits24(first) and s[-24:] == bits24(last), (prn, "secondary")
    assert re.search(r"bit values of\s+00010 in binary", text)
    assert bds_b2a.DATA_SECONDARY == (0, 0, 0, 1, 0)

    src = f"BDS-SIS-ICD-B2a-{ver.group(1)} ({ver.group(2)}), PDF sha256 {digest}"
    out = ROOT / "model" / "bdmodel" / "tables" / "bds_b2a_table.py"
    body = [f"# Generated by tools/import_bds_b2a.py from {src},",
            "# Tables 5-2, 5-3 and 5-4. Do not edit.",
            "# B2A_CODES[prn] = {'D': data register-2 initial bits, 'P': pilot register-2",
            "#                   initial bits, 'S': (Weil phase difference w, truncation point p)}",
            "B2A_CODES = {"]
    body += [f"    {p}: {{\"D\": \"{data[p][0]}\", \"P\": \"{pilot[p][0]}\", "
             f"\"S\": ({int(sec[p][0])}, {int(sec[p][1])})}}," for p in range(1, 64)]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out}: 126 primary codes and 63 pilot secondary codes match their printed "
          f"first/last 24 chips ({src})")


if __name__ == "__main__":
    main()
