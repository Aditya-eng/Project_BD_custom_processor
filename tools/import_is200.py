#!/usr/bin/env python3
"""Import L2C code tables from the official IS-GPS-200N PDF (needs poppler-utils: pdftotext).

usage: import_is200.py <IS-GPS-200N.pdf>  -> model/bdmodel/tables/gps_l2c_table.py

Rows come from Table 3-IIa (PRN 1-37), Table 3-IIb (PRN 38-63) and Table 6-II
(PRN 159-210), each giving the CM and CL initial and end register states in octal.
Nothing is written unless, for every row and both codes, the generator in
model/bdmodel/gps_l2c.py started from the initial state reaches the printed end
state after (period - 1) clocks: 10229 for CM, 767249 for CL. That exercises the
polynomial, the register convention and every parsed digit.
"""
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
from bdmodel.gps_l2c import CL_LEN, CM_LEN, srg  # noqa: E402

TITLES = (r"^Table 3-IIa\. Code Phase Assignments \(IIR-M, IIF, and subsequent blocks only\) \(sheet \d of 2\)$",
          r"^Table 3-IIb\. Expanded Code Phase Assignments \(GPS III, GPS IIIF, and subsequent blocks only\)$",
          r"^Table 6-II\. Additional L2 CM-/L2 CL-Code Phase Assignments \(sheet \d of 2\)$")
OCT = r"([0-7]{9})"


def main():
    pdf = Path(sys.argv[1])
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], check=True,
                          capture_output=True, text=True).stdout
    lines = [re.sub(r"[ \t]+", " ", l.strip()) for l in text.splitlines()]
    issue = re.search(r"IS-GPS-200([A-Z])\s*\n\s*(\d{2}-[A-Z]{3}-\d{4})", text)

    rows = {}
    for title, sv_col in zip(TITLES, (True, True, False)):
        heads = [i for i, l in enumerate(lines) if re.match(title, l)]
        assert heads, title
        for h in heads:
            for l in lines[h + 1:h + 60]:
                if "Short cycled period" in l:
                    break
                pat = (r"(\d+) " if sv_col else "") + r"(\d+) " + " ".join([OCT] * 4)
                m = re.fullmatch(pat, l)
                if m:
                    g = m.groups()[1:] if sv_col else m.groups()
                    prn = int(g[0])
                    assert prn not in rows, prn
                    rows[prn] = tuple(int(v, 8) for v in g[1:])
    expect = list(range(1, 64)) + list(range(159, 211))
    assert sorted(rows) == expect, sorted(set(expect) ^ set(rows))

    for prn, (cm0, cl0, cm_end, cl_end) in rows.items():
        assert srg(cm0, CM_LEN - 1)[1] == cm_end, ("CM", prn)
        assert srg(cl0, CL_LEN - 1)[1] == cl_end, ("CL", prn)

    src = f"IS-GPS-200{issue.group(1)} ({issue.group(2)}), PDF sha256 {digest}" if issue else digest
    out = ROOT / "model" / "bdmodel" / "tables" / "gps_l2c_table.py"
    body = [f"# Generated by tools/import_is200.py from {src},",
            "# Tables 3-IIa, 3-IIb and 6-II. Do not edit.",
            "# L2C_CODES[prn] = (CM initial, CL initial, CM end, CL end) register states",
            "L2C_CODES = {"]
    body += [f"    {p}: (0o{v[0]:09o}, 0o{v[1]:09o}, 0o{v[2]:09o}, 0o{v[3]:09o}),"
             for p, v in sorted(rows.items())]
    body += ["}", ""]
    out.write_text("\n".join(body))
    print(f"wrote {out}: {len(rows)} PRNs, CM and CL end states verified ({src})")


if __name__ == "__main__":
    main()
